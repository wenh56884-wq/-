def validate():
    """调用方（seed_mock.py / tests）启动前自检：学院与专业映射完整、无孤儿专业。"""
    errs = []
    known = set(COLLEGES)
    for major, (college, _, courses) in MAJORS.items():
        if college not in known:
            errs.append(f"major '{major}' 指向未知学院 '{college}'")
        if not courses:
            errs.append(f"major '{major}' 课程为空")
    for major in JOB_KEYWORDS:
        if major not in MAJORS:
            errs.append(f"JOB_KEYWORDS 含未登记专业 '{major}'")
    for major in MAJORS:
        if major not in JOB_KEYWORDS:
            errs.append(f"专业 '{major}' 缺少 JOB_KEYWORDS 映射")
    return errs


