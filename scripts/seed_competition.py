# 栏目页抓取：只解析官方页面里已有的标题 + 日期 + 链接，不做任何推断补全
# ------------------------------------------------------------------
def fetch_notices() -> list[dict[str, Any]]:
    import urllib.request

    req = urllib.request.Request(
        CHANNEL_URL, headers={"User-Agent": "Mozilla/5.0 (qihang-competition-sync)"})
    html = urllib.request.urlopen(req, timeout=20).read().decode("utf-8", "ignore")

    notices: list[dict[str, Any]] = []
    # 栏目页结构：<a href="文章链接" title="通知标题"> … <p class="p1">10-20</p> <p class="p2">2026</p>
    for match in re.finditer(
            r'<a\s+href="([^"]+)"\s+title="([^"]+)"[^>]*>.*?'
            r'<p\s+class="p1">\s*(\d{2}-\d{2})\s*</p>.*?'
            r'<p\s+class="p2">\s*(\d{4})\s*</p>',
            html, re.S):
        href, title, month_day, year = match.groups()
        title = title.strip()
        # 栏目页顶部还挂着「实践教学 / 学科竞赛」这类导航链接，不是通知，剔除
        if len(title) < 8 or title in ("实践教学", "专业实践", "学科竞赛"):
            continue
        url = href if href.startswith("http") else f"http://www.cfec.edu.cn{href}"
        notices.append({
            "title": title,
            "published_at": f"{year}-{month_day}",
            "url": url,
        })
    return notices


def save_notices(notices: list[dict[str, Any]]) -> int:
    """落库一批通知，返回**真正新增**的条数（已存在的只更新链接，不计入推送）。

    用 INSERT ... ON DUPLICATE KEY UPDATE + 受影响行数判断：
    MySQL 对「插入」返回 1、「仅更新」返回 2，据此区分新旧，避免重复推送。
    """
    if not notices:
        return 0
    conn = _connect()
    added = 0
    try:
        with conn.cursor() as cur:
            for item in notices:
                affected = cur.execute(
                    "INSERT INTO competition_notice (title, published_at, url, source) VALUES "
                    "(%s, %s, %s, 'cfec-jwc') ON DUPLICATE KEY UPDATE url=VALUES(url)",
                    (item["title"], item["published_at"], item["url"]),
                )
                if affected == 1:  # 1=新插入；2=已存在被更新；0=无变化
                    added += 1
        conn.commit()
    finally:
        conn.close()
    return added


def seed_notices() -> int:
    """抓取栏目页最新通知；抓不到就原样返回 0（绝不写入编造数据）。"""
    try:
        notices = fetch_notices()
    except Exception as exc:  # 网络不可用时只告警，保持库里的数据仍是官方原文
        print(f"[warn] 抓取栏目页失败，跳过通知同步：{exc}")
        return 0
    if not notices:
        print("[warn] 栏目页未解析出通知，跳过")
        return 0
    return save_notices(notices)


def ensure_columns() -> None:
    """补列：老库上新建的 student_notice_read 可能还没有 last_notice_id（水位改用 id）。"""
    conn = _connect()
    try:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT COUNT(*) AS n FROM information_schema.COLUMNS "
                "WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'student_notice_read' "
                "AND COLUMN_NAME = 'last_notice_id'")
            if int((cur.fetchone() or {}).get("n") or 0) == 0:
                cur.execute(
                    "ALTER TABLE student_notice_read "
                    "ADD COLUMN last_notice_id BIGINT NOT NULL DEFAULT 0 "
                    "COMMENT '已读到的通知 id（判未读用）' AFTER last_read_at")
        conn.commit()
    finally:
        conn.close()


def main() -> None:
    parser = argparse.ArgumentParser(description="灌入重庆财经学院官方竞赛数据")
    parser.add_argument("--fetch", action="store_true", help="同时抓取栏目页最新参赛通知")
    args = parser.parse_args()

    apply_schema()
    ensure_columns()
    print(f"[ok] 竞赛名单写入/更新：{seed_plan()} 条")
    print(f"     来源：{PLAN_TITLE}（{PLAN_DATE}）\n     {PLAN_URL}")
    if args.fetch:
        print(f"[ok] 最新通知同步：{seed_notices()} 条（来源 {CHANNEL_URL}）")


if __name__ == "__main__":
    main()
