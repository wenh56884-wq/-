def _connect() -> pymysql.connections.Connection:
    s = get_settings()
    return pymysql.connect(host=s.mysql_host, port=s.mysql_port, user=s.mysql_user,
                           password=s.mysql_password, database=s.mysql_db,
                           charset="utf8mb4", cursorclass=pymysql.cursors.DictCursor,
                           connect_timeout=5)


def apply_schema() -> None:
    """执行建表 DDL：先剥掉整行注释，避免出现「注释 + CREATE」被误判跳过的情况。"""
    raw = (Path(__file__).resolve().parents[1] / "db" / "competition_tables.sql").read_text(
        encoding="utf-8")
    lines = [line for line in raw.splitlines() if not line.lstrip().startswith("--")]
    conn = _connect()
    try:
        with conn.cursor() as cur:
            for stmt in (s.strip() for s in "\n".join(lines).split(";") if s.strip()):
                if stmt.upper().startswith("CREATE"):
                    cur.execute(stmt)
        conn.commit()
    finally:
        conn.close()


def seed_plan() -> int:
    """灌入官方计划项目名单（同名按唯一键更新，重复运行幂等）。"""
    conn = _connect()
    written = 0
    try:
        with conn.cursor() as cur:
            for name, category, org_unit, track, tags, reward in ROWS:
                cur.execute(
                    "INSERT INTO competition (name, category, org_unit, track, tags_json, "
                    "reward, source_title, source_url, published_at) VALUES "
                    "(%s, %s, %s, %s, %s, %s, %s, %s, %s) "
                    "ON DUPLICATE KEY UPDATE category=VALUES(category), "
                    "org_unit=VALUES(org_unit), track=VALUES(track), tags_json=VALUES(tags_json), "
                    "reward=VALUES(reward), source_title=VALUES(source_title), "
                    "source_url=VALUES(source_url), published_at=VALUES(published_at)",
                    (name, category, org_unit, track,
                     json.dumps(tags, ensure_ascii=False), reward,
                     PLAN_TITLE, PLAN_URL, PLAN_DATE),
                )
                written += 1
        conn.commit()
    finally:
        conn.close()
    return written


