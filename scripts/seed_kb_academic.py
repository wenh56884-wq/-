# 早期演示时灌的企业制度文档：与「学业职业规划」主题不符，--purge-legacy 会清掉
LEGACY_TITLES = ("reimbursement_policy", "员工报销制度", "请假与考勤制度", "采购与付款流程")


def main() -> None:
    purge = "--purge-legacy" in sys.argv
    client = TestClient(create_app())
    r = client.post("/auth/login", json={"role": "teacher", "account": "T001",
                                         "password": "teacher@123"})
    if r.status_code != 200:
        print(f"教师登录失败：{r.status_code} {r.text[:200]}")
        return
    headers = {"Authorization": f"Bearer {r.json()['access_token']}"}

    docs = client.get("/kb/docs", headers=headers).json().get("items") or []
    if purge:
        for d in docs:
            if d["title"] in LEGACY_TITLES:
                resp = client.delete(f"/kb/docs/{d['id']}", headers=headers)
                print(f"  [删除] {d['title']}（{'OK' if resp.status_code == 200 else resp.status_code}）")
        docs = client.get("/kb/docs", headers=headers).json().get("items") or []

    existing = {d["title"] for d in docs}

    added = skipped = 0
    for title, text in DOCS + EXTRA_DOCS + JOB_DOCS:
        if title in existing:
            print(f"  [跳过] {title}（已存在）")
            skipped += 1
            continue
        resp = client.post("/kb/docs/text", headers=headers,
                           json={"title": title, "text": text, "source_type": "txt"})
        if resp.status_code != 200:
            print(f"  [失败] {title}：{resp.status_code} {resp.text[:160]}")
            continue
        body = resp.json()
        print(f"  [OK] {title}  分块={body.get('chunks')}  字数={len(text)}")
        added += 1

    total = client.get("/kb/docs", headers=headers).json().get("total")
    print(f"\n新增 {added} 份，跳过 {skipped} 份；知识库现有 {total} 份文档。")


if __name__ == "__main__":
    main()
