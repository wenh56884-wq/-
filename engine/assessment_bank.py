# 五级 Likert：正向题文案（非常不符合→非常符合）
LIKERT5 = {"A": "非常不符合", "B": "不太符合", "C": "一般", "D": "比较符合", "E": "非常符合"}
# 反向题文案（非常符合→非常不符合）；scoring 仍 A=1..E=5，实现反向计分
LIKERT5R = {"A": "非常符合", "B": "比较符合", "C": "一般", "D": "不太符合", "E": "非常不符合"}
# 五级 Likert 分值（正向题与反向题共用：反向靠「文案倒序 + 分值不变」实现）
L5 = {"A": 1, "B": 2, "C": 3, "D": 4, "E": 5}


def _q(category: str, dimension: str, content: str,
       options: dict[str, str], scoring: dict[str, int]) -> dict[str, Any]:
    return {"category": category, "dimension": dimension, "content": content,
            "options": options, "scoring": scoring}


def _likert(dimension: str, content: str, reverse: bool = False) -> dict[str, Any]:
    """生成一道五级 Likert 题：reverse=True 时文案倒序实现反向计分。"""
    return _q("性格特质" if dimension in ("外向性", "尽责性", "开放性", "情绪稳定性", "宜人性")
              else "职业兴趣", dimension, content,
              LIKERT5R if reverse else LIKERT5, L5)


