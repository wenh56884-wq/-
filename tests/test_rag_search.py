def test_colloquial_fail_and_graduate_hits_xueji_or_exam():
    """「挂科了还能毕业吗」必须召回学籍/考核文档——答案（补考/重修/毕业学分）在那里。

    2026-10-29 实测：当前只召回实习/就业文档，正确文档没进 top2。
    这条用例先按「问题存在」落住，修复后自动转绿。
    """
    titles = _top_titles("挂科了还能毕业吗")
    assert any(("学籍" in t or "考核" in t) for t in titles), (
        f"口语问句没召回学籍/考核文档，只召回了 {titles}"
    )


def test_colloquial_retake_hits_xueji_or_exam():
    titles = _top_titles("补考没过怎么办")
    assert any(t in ("学籍与学分管理规定", "课程考核与成绩管理办法") for t in titles), titles


