def _rows() -> list[dict]:
    out = []
    for i, (title, text) in enumerate(_DOCS.items(), start=1):
        out.append({"doc_id": i, "title": title, "chunk_no": 1,
                    "page": None, "text": text})
    return out


def _top_titles(query: str, top_k: int = 3) -> list[str]:
    hits = rag.search(query, _rows(), top_k=top_k)
    return [h["title"] for h in hits]


# ----------------------------------------------------------------
# 1. 基本功能：关键词问法必须命中正确文档
# ----------------------------------------------------------------
def test_keyword_query_hits_right_doc():
    titles = _top_titles("红色预警面谈时限")
    assert titles, "关键词问题必须命中"
    assert titles[0] == "学业预警与帮扶管理办法", titles


def test_graduation_credit_query_hits_xueji():
    titles = _top_titles("毕业最低总学分是多少")
    assert titles and titles[0] == "学籍与学分管理规定", titles


# ----------------------------------------------------------------
# 2. 无关问题：宁可不命中，也不拼凑
# ----------------------------------------------------------------
def test_unrelated_queries_return_empty():
    for q in ("红烧肉怎么做", "今天天气怎么样", "帮我写一首关于月亮的诗"):
        assert _top_titles(q) == [], f"无关问题「{q}」不该召回任何文档"


def test_relative_head_filter_drops_noise():
    """比 top1 低 45% 以上的命中视为噪声，不该混进结果（rag.search 注释承诺的行为）。"""
    hits = rag.search("量子纠缠的原理", _rows(), top_k=5)
    if len(hits) >= 2:
        top = hits[0]["score"]
        tail = [h["score"] for h in hits[1:]]
        assert all(s >= top * 0.45 for s in tail), (
            f"相对头部过滤失效：top={top:.3f}，尾部={tail}"
        )


