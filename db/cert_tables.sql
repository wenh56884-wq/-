-- db/cert_tables.sql
-- 考证中心：大学生考证目录（真实有效数据）+ 已读水位复用竞赛通知机制
-- 数据规则：
--   1. 每条记录必须带 负责机构 / 官网 / 来源链接 / 核实日期，可逐条点开核对；
--   2. 报名与考试日期为官方已公布的写实值；未公布的写"预计"并在 日期备注 里说明依据；
--   3. 表可重复执行（CREATE IF NOT EXISTS + INSERT ON DUPLICATE KEY UPDATE），
--      官网更新批次后改本文件即可，重跑自动刷新；
--   4. 数据核实日期：2026-11-19（官方公告逐条核对）。

CREATE TABLE IF NOT EXISTS `考证目录` (
  `编号`        BIGINT AUTO_INCREMENT PRIMARY KEY,
  `考证名称`    VARCHAR(120) NOT NULL COMMENT '证书全称（官方原文）',
  `简称`        VARCHAR(60)  NOT NULL COMMENT '学生口语叫法（检索用）',
  `负责机构`    VARCHAR(120) NOT NULL COMMENT '主办方（官方原文）',
  `级别科目`    VARCHAR(200) NOT NULL COMMENT '推荐级别/科目',
  `适合去向`    VARCHAR(120) NOT NULL COMMENT 'JSON数组：就业/考公/考研/升学/通用',
  `适合标签`    TEXT         NOT NULL COMMENT '专业/年级/方向标签 JSON数组',
  `前提条件`    TEXT         NOT NULL COMMENT '报名前提（差什么才报得了）',
  `收获`        TEXT         NOT NULL COMMENT '考取后可以获得什么',
  `报名方式`    TEXT         NOT NULL COMMENT '如何报名（步骤级说明）',
  `报名官网`    VARCHAR(300) NOT NULL COMMENT '官方报名入口',
  `费用说明`    VARCHAR(200) NULL,
  `报名开始`    DATE         NULL COMMENT '最近一批报名开始（常年可报为 NULL）',
  `报名截止`    DATE         NULL,
  `考试日期`    VARCHAR(200) NOT NULL COMMENT '最近一批考试日期（原文级）',
  `考试开始`    DATE         NULL COMMENT '最近一批考试首日（机器可读，常年可报为 NULL）',
  `日期备注`    VARCHAR(400) NULL COMMENT '哪些日期为预计及依据',
  `批次说明`    VARCHAR(300) NOT NULL COMMENT '每年几批、错过等下一批的说明',
  `含金量`      VARCHAR(16)  NOT NULL COMMENT '必备/推荐/加分',
  `来源标题`    VARCHAR(200) NOT NULL COMMENT '信息来源标题',
  `来源链接`    VARCHAR(300) NOT NULL COMMENT '信息来源链接（可点开核对）',
  `核实日期`    DATE         NOT NULL,
  `排序`        INT          NOT NULL DEFAULT 100,
  UNIQUE KEY uk_cert_name (`考证名称`),
  KEY idx_cert_level (`含金量`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='大学生考证目录（官方来源，可核对）';

